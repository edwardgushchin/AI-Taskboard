const { contextBridge, ipcRenderer, webUtils } = require("electron");

contextBridge.exposeInMainWorld("taskboard", {
  openFileLink: link => ipcRenderer.invoke("board:openFileLink", link),
  filePayload: async file => {
    if (file.link) return { name: file.name, type: file.type, link: file.link, bytes: new ArrayBuffer(0) };
    const path = webUtils.getPathForFile(file);
    if (path) return { name: file.name, type: file.type, link: await ipcRenderer.invoke("board:fileLink", path), bytes: new ArrayBuffer(0) };
    if (file.size > 64 * 1024 * 1024) throw new Error("This file has no local path. Save it locally and attach it again.");
    return { name: file.name, type: file.type, bytes: await file.arrayBuffer() };
  },
  bootstrap: () => ipcRenderer.invoke("board:bootstrap"),
  open: () => ipcRenderer.invoke("board:open"),
  boardRequest: (request, files, project, goal, immediate, id, goalRunId) => ipcRenderer.invoke("board:request", request, files, project, goal, immediate, id, goalRunId),
  boardHistory: (project, cursor, view) => ipcRenderer.invoke("board:history", project, cursor, view),
  readManagerMessages: (project, ids) => ipcRenderer.invoke("board:readManagerMessages", project, ids),
  taskRunHistory: id => ipcRenderer.invoke("board:taskRunHistory", id),
  reviewerChat: id => ipcRenderer.invoke("board:reviewerChat", id),
  boardQueue: (project, action, id, draft, goal, files) => ipcRenderer.invoke("board:queue", project, action, id, draft, goal, files),
  boardGoal: (kind, objective) => ipcRenderer.invoke("board:goal", kind, objective),
  answerBoardQuestion: (id, answer) => ipcRenderer.invoke("board:answerQuestion", id, answer),
  taskLimits: limits => ipcRenderer.invoke("agents:limits", limits),
  stopOrchestrator: () => ipcRenderer.invoke("board:stopOrchestrator"),
  chatModels: () => ipcRenderer.invoke("chat:models"),
  transcribeVoice: (samples, language) => ipcRenderer.invoke("chat:transcribeVoice", samples, language),
  windowsSpeech: (action, language) => ipcRenderer.invoke("chat:windowsSpeech", action, language),
  chatStop: id => ipcRenderer.invoke("chat:stop", id),
  chatSend: (id, request) => ipcRenderer.invoke("chat:send", id, request),
  retryDraftDiscussion: id => ipcRenderer.invoke("chat:retry-draft-discussion", id),
  onChatUpdate: listener => { ipcRenderer.on("chat:update", (_event, update) => listener(update)); },
  createBoard: type => ipcRenderer.invoke("board:create", type),
  openRecent: path => ipcRenderer.invoke("board:recent", path),
  selectTab: project => ipcRenderer.invoke("board:selectTab", project),
  reorderTab: (project, target, after) => ipcRenderer.invoke("board:reorderTab", project, target, after),
  closeTab: project => ipcRenderer.invoke("board:closeTab", project),
  menuAction: action => ipcRenderer.invoke("menu:action", action),
  checkUpdates: () => ipcRenderer.invoke("app:checkUpdates"),
  customTitleBar: process.platform === "win32",
  isMac: process.platform === "darwin",
  isWindows: process.platform === "win32",
  command: (action, id, input) => ipcRenderer.invoke("board:command", action, id, input),
  saveAttachment: (id, file, name) => ipcRenderer.invoke("board:saveAttachment", id, file, name),
  attachmentPreview: (id, file) => ipcRenderer.invoke("board:attachmentPreview", id, file),
  artifactPreview: path => ipcRenderer.invoke("board:artifactPreview", path),
  runImagePreview: (id, path) => ipcRenderer.invoke("board:runImagePreview", id, path),
  saveRunImage: (id, path) => ipcRenderer.invoke("board:saveRunImage", id, path),
  openLink: url => ipcRenderer.invoke("chat:openLink", url),
  readMarkdown: (id, link, source) => ipcRenderer.invoke("board:readMarkdown", id, link, source),
  openWorktree: id => ipcRenderer.invoke("board:openWorktree", id),
  revealArtifact: (id, source, sha256) => ipcRenderer.invoke("board:revealArtifact", id, source, sha256),
  launchTask: (id, options) => ipcRenderer.invoke("board:launchTask", id, options),
  subscribe: listener => { ipcRenderer.on("board:changed", (_event, frame) => listener(frame)); },
  themes: () => ipcRenderer.invoke("appearance:themes"),
  setLanguage: language => ipcRenderer.invoke("appearance:language", language),
  setTheme: theme => ipcRenderer.invoke("appearance:theme", theme),
  onTheme: listener => { ipcRenderer.on("appearance:changed", (_event, theme) => listener(theme)); },
  onProviderLimitsChanged: listener => { ipcRenderer.on("providers:changed", () => listener()); },
  providerLimits: () => ipcRenderer.invoke("providers:limits"),
  codexStatus: () => ipcRenderer.invoke("codex:status"),
  executionModels: () => ipcRenderer.invoke("codex:executionModels"),
  setTaskAccess: (project, id, createdAt, fullAccess) => ipcRenderer.invoke("codex:taskAccess", project, id, createdAt, fullAccess),
  setManagerAccess: (project, mode) => ipcRenderer.invoke("codex:managerAccess", project, mode),
  chooseCodex: () => ipcRenderer.invoke("codex:choose"),
  autoDetectCodex: () => ipcRenderer.invoke("codex:auto"),
  setCodexWindowsSandbox: mode => ipcRenderer.invoke("codex:windowsSandbox", mode),
});
